bool scaler_from_gain_db(float gain_db, float& scaler) {
    scaler = 0.0f;
    if (std::isnan(gain_db))
        return false;
    if (gain_db >= 144.0f) {
        scaler = 0.0f;
        return true;
    }
    scaler = std::pow(10.0f, gain_db * -0.05f);
    return !std::isnan(scaler);
}

bool scaler_from_index(std::uint8_t index, float& scaler) {
    scaler = 0.0f;
    if (index == 0xFFu) {
        scaler = std::numeric_limits<float>::infinity();
        return true;
    }
    if (index > 0xF0u)
        return false;
    scaler = kScalerTable[index];
    return true;
}

bool scaler_to_index(
    float requested,
    std::uint8_t& index,
    float& scaler) {
    index = 0u;
    scaler = 0.0f;
    if (!std::isfinite(requested)
        || requested < 1.0f || requested > 16.0f) {
        return false;
    }
    const auto* begin = kScalerTable;
    const auto* end =
        kScalerTable
        + sizeof(kScalerTable) / sizeof(kScalerTable[0]);
    const auto* selected = std::lower_bound(begin, end, requested);
    if (selected == end)
        return false;
    index = static_cast<std::uint8_t>(selected - begin);
    scaler = *selected;
    return true;
}

std::uint8_t validate_scaler_index(std::uint8_t index) {
    return index < 0xF0u ? index : 0xF0u;
}

